/* 출력 백엔드의 대답 표. 장치가 없는 자리를 읽으면 PCI 는 전부 1 을 돌려준다
   (TRACE_DEFAULT). 장치 0 은 QEMU 의 edu 처럼 대답한다: BAR0 하나가 1 MiB, 능력은 MSI 하나,
   BAR0 의 레지스터는 신분 값과 5! 을 낸다. */
#define TRACE_DEFAULT 0xFFFFFFFFu
#define C(off) (0x30000000u + (off))
static const struct { uintptr_t addr; unsigned n; uint32_t values[4]; } replies[] = {
    { C(0x00), 1, { 0x11e81234u } },               /* 제조사 1234, 장치 11e8 */
    { C(0x04), 1, { 0x00100000u } },               /* 명령 0, 상태: 능력 목록 있음 */
    { C(0x08), 1, { 0x00ff0010u } },
    { C(0x0C), 1, { 0x00000000u } },               /* 머리말 종류 0, 기능 하나 */
    { C(0x10), 2, { 0x00000000u, 0xfff00000u } },  /* 처음 0, 전부 1 을 쓴 뒤 1 MiB */
    { C(0x14), 1, { 0 } }, { C(0x18), 1, { 0 } }, { C(0x1C), 1, { 0 } },
    { C(0x20), 1, { 0 } }, { C(0x24), 1, { 0 } },  /* 나머지 BAR 는 없다 */
    { C(0x34), 1, { 0x00000040u } },
    { C(0x40), 1, { 0x00000005u } },               /* MSI, 다음 없음 */
    { 0x40000000u, 1, { 0x010000edu } },           /* edu 신분 레지스터 */
    { 0x40000008u, 1, { 120u } },                  /* 5! */
    { 0x40000020u, 2, { 1u, 0u } },                /* 한 번은 바쁘고 다음엔 끝 */
};
