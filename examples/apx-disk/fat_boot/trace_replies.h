/* 출력 백엔드의 대답 표. 마지막 창(0x1000_8000)만 virtio 블록 장치라고 대답한다.
   상태 레지스터는 마지막으로 쓴 값이 돌아오므로 FEATURES_OK 를 받아들인 것이 된다.
   그러나 섹터 내용은 장치가 기억 장치에 DMA 로 쓰는 것이라, 이 표로는 흉내 낼 수 없다. */
#define V(off) (0x10008000u + (off))
static const struct { uintptr_t addr; unsigned n; uint32_t values[4]; } replies[] = {
    { V(0x000), 1, { 0x74726976u } },     /* "virt" */
    { V(0x004), 1, { 2u } },              /* virtio-mmio 판 2 */
    { V(0x008), 1, { 2u } },              /* 장치 종류 2 = 블록 */
    { V(0x010), 1, { 1u } },              /* 기능 비트 32 = VERSION_1 */
    { V(0x034), 1, { 256u } },            /* 고리 길이 최대 */
    { V(0x100), 1, { 131072u } },         /* 용량: 64 MiB */
    { V(0x104), 1, { 0u } },
};
